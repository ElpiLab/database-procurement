CREATE TABLE SUPPLIER (
    supplier_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    VARCHAR2(150) NOT NULL,
    email                   VARCHAR2(150) NOT NULL UNIQUE,
    phone                   VARCHAR2(50),
    street                  VARCHAR2(150),
    zip_code                VARCHAR2(20),
    city                    VARCHAR2(100),
    country                 VARCHAR2(50) DEFAULT 'Switzerland' NOT NULL,
    last_invoice_date       DATE,
    code_of_conduct_status  VARCHAR2(20) DEFAULT 'REQUESTED' NOT NULL 
                            CHECK (code_of_conduct_status IN ('ACCEPTED', 'REJECTED', 'REQUESTED'))
);

CREATE TABLE PRODUCT (
    product_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR2(150) NOT NULL,
    category        VARCHAR2(100) NOT NULL,
    stock           INTEGER NOT NULL CHECK (stock >= 0),
    min_stock       INTEGER NOT NULL CHECK (min_stock >= 0),
    is_sterile      CHAR(1) DEFAULT 'N' NOT NULL CHECK (is_sterile IN ('Y', 'N'))
);

CREATE TABLE SUPPLIER_PRODUCT (
    supplier_id     INTEGER NOT NULL,
    product_id      INTEGER NOT NULL,
    catalog_number  VARCHAR2(100),
    lead_time_days  INTEGER CHECK (lead_time_days >= 0),
    unit_price      NUMBER(10, 2) NOT NULL CHECK (unit_price >= 0),
    priority        INTEGER DEFAULT 1 NOT NULL CHECK (priority IN (1, 2)),
    CONSTRAINT pk_supplier_product PRIMARY KEY (supplier_id, product_id),
    CONSTRAINT fk_sp_supplier FOREIGN KEY (supplier_id) REFERENCES SUPPLIER(supplier_id),
    CONSTRAINT fk_sp_product FOREIGN KEY (product_id) REFERENCES PRODUCT(product_id)
);

CREATE TABLE DEPARTMENT (
    department_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR2(100) NOT NULL UNIQUE,
    cost_center     VARCHAR2(50) NOT NULL UNIQUE,
    building        VARCHAR2(100)
);

CREATE TABLE EMPLOYEE (
    employee_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name      VARCHAR2(100) NOT NULL,
    last_name       VARCHAR2(100) NOT NULL,
    email           VARCHAR2(150) NOT NULL UNIQUE,
    role            VARCHAR2(100) NOT NULL,
    department_id   INTEGER NOT NULL,
    CONSTRAINT fk_emp_department FOREIGN KEY (department_id) REFERENCES DEPARTMENT(department_id)
);

CREATE TABLE PURCHASE_ORDER (
    order_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date      DATE DEFAULT SYSDATE NOT NULL,
    delivery_date   DATE,
    shipping_cost   NUMBER(10, 2) DEFAULT 0.00 NOT NULL CHECK (shipping_cost >= 0),
    status          VARCHAR2(50) NOT NULL CHECK (status IN ('DRAFT', 'ORDERED', 'DELIVERED', 'CANCELLED')),
    supplier_id     INTEGER NOT NULL,
    employee_id     INTEGER NOT NULL,
    CONSTRAINT fk_po_supplier FOREIGN KEY (supplier_id) REFERENCES SUPPLIER(supplier_id),
    CONSTRAINT fk_po_employee FOREIGN KEY (employee_id) REFERENCES EMPLOYEE(employee_id)
);

CREATE TABLE ORDER_POSITION (
    order_id            INTEGER NOT NULL,
    product_id          INTEGER NOT NULL,
    quantity            INTEGER NOT NULL CHECK (quantity > 0),
    unit_price_at_order NUMBER(10, 2) NOT NULL CHECK (unit_price_at_order >= 0),
    CONSTRAINT pk_order_position PRIMARY KEY (order_id, product_id),
    CONSTRAINT fk_op_order FOREIGN KEY (order_id) REFERENCES PURCHASE_ORDER(order_id) ON DELETE CASCADE,
    CONSTRAINT fk_op_product FOREIGN KEY (product_id) REFERENCES PRODUCT(product_id)
);
