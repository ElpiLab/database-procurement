CREATE TABLE KSBL_SUPPLIER (
    supplier_id             INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name                    VARCHAR2(150) NOT NULL,
    email                   VARCHAR2(150) NOT NULL,
    phone                   VARCHAR2(50),
    street                  VARCHAR2(150),
    zip_code                VARCHAR2(20),
    city                    VARCHAR2(100),
    country                 VARCHAR2(50) DEFAULT 'Switzerland' NOT NULL,
    last_invoice_date       DATE,
    code_of_conduct_status  VARCHAR2(20) DEFAULT 'REQUESTED' NOT NULL,
    CONSTRAINT ksbl_pk_supplier PRIMARY KEY (supplier_id),
    CONSTRAINT ksbl_uq_supplier_email UNIQUE (email),
    CONSTRAINT ksbl_ck_supplier_conduct CHECK (code_of_conduct_status IN ('ACCEPTED', 'REJECTED', 'REQUESTED'))
);

CREATE TABLE KSBL_PRODUCT (
    product_id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name            VARCHAR2(150) NOT NULL,
    category        VARCHAR2(100) NOT NULL,
    stock           INTEGER NOT NULL,
    min_stock       INTEGER NOT NULL,
    is_sterile      CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT ksbl_pk_product PRIMARY KEY (product_id),
    CONSTRAINT ksbl_ck_product_stock CHECK (stock >= 0),
    CONSTRAINT ksbl_ck_product_min_stock CHECK (min_stock >= 0),
    CONSTRAINT ksbl_ck_product_sterile CHECK (is_sterile IN ('Y', 'N'))
);

CREATE TABLE KSBL_SUPPLIER_PRODUCT (
    supplier_id     INTEGER NOT NULL,
    product_id      INTEGER NOT NULL,
    catalog_number  VARCHAR2(100),
    lead_time_days  INTEGER,
    unit_price      NUMBER(10, 2) NOT NULL,
    priority        INTEGER DEFAULT 1 NOT NULL,
    CONSTRAINT ksbl_pk_supplier_product PRIMARY KEY (supplier_id, product_id),
    CONSTRAINT ksbl_fk_sp_supplier FOREIGN KEY (supplier_id) REFERENCES KSBL_SUPPLIER(supplier_id),
    CONSTRAINT ksbl_fk_sp_product FOREIGN KEY (product_id) REFERENCES KSBL_PRODUCT(product_id),
    CONSTRAINT ksbl_ck_sp_lead_time CHECK (lead_time_days >= 0),
    CONSTRAINT ksbl_ck_sp_price CHECK (unit_price >= 0),
    CONSTRAINT ksbl_ck_sp_priority CHECK (priority IN (1, 2))
);

CREATE TABLE KSBL_DEPARTMENT (
    department_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name            VARCHAR2(100) NOT NULL,
    cost_center     VARCHAR2(50) NOT NULL,
    building        VARCHAR2(100),
    CONSTRAINT ksbl_pk_department PRIMARY KEY (department_id),
    CONSTRAINT ksbl_uq_department_name UNIQUE (name),
    CONSTRAINT ksbl_uq_department_cost_center UNIQUE (cost_center)
);

CREATE TABLE KSBL_EMPLOYEE (
    employee_id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    first_name      VARCHAR2(100) NOT NULL,
    last_name       VARCHAR2(100) NOT NULL,
    email           VARCHAR2(150) NOT NULL,
    role            VARCHAR2(100) NOT NULL,
    department_id   INTEGER NOT NULL,
    CONSTRAINT ksbl_pk_employee PRIMARY KEY (employee_id),
    CONSTRAINT ksbl_uq_employee_email UNIQUE (email),
    CONSTRAINT ksbl_fk_emp_department FOREIGN KEY (department_id) REFERENCES KSBL_DEPARTMENT(department_id)
);

CREATE TABLE KSBL_PURCHASE_ORDER (
    order_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    order_date      DATE DEFAULT SYSDATE NOT NULL,
    delivery_date   DATE,
    shipping_cost   NUMBER(10, 2) DEFAULT 0.00 NOT NULL,
    status          VARCHAR2(50) NOT NULL,
    supplier_id     INTEGER NOT NULL,
    employee_id     INTEGER NOT NULL,
    CONSTRAINT ksbl_pk_purchase_order PRIMARY KEY (order_id),
    CONSTRAINT ksbl_fk_po_supplier FOREIGN KEY (supplier_id) REFERENCES KSBL_SUPPLIER(supplier_id),
    CONSTRAINT ksbl_fk_po_employee FOREIGN KEY (employee_id) REFERENCES KSBL_EMPLOYEE(employee_id),
    CONSTRAINT ksbl_ck_po_shipping_cost CHECK (shipping_cost >= 0),
    CONSTRAINT ksbl_ck_po_status CHECK (status IN ('DRAFT', 'ORDERED', 'DELIVERED', 'CANCELLED'))
);

CREATE TABLE KSBL_ORDER_POSITION (
    order_id            INTEGER NOT NULL,
    product_id          INTEGER NOT NULL,
    quantity            INTEGER NOT NULL,
    unit_price_at_order NUMBER(10, 2) NOT NULL,
    CONSTRAINT ksbl_pk_order_position PRIMARY KEY (order_id, product_id),
    CONSTRAINT ksbl_fk_op_order FOREIGN KEY (order_id) REFERENCES KSBL_PURCHASE_ORDER(order_id) ON DELETE CASCADE,
    CONSTRAINT ksbl_fk_op_product FOREIGN KEY (product_id) REFERENCES KSBL_PRODUCT(product_id),
    CONSTRAINT ksbl_ck_op_quantity CHECK (quantity > 0),
    CONSTRAINT ksbl_ck_op_price CHECK (unit_price_at_order >= 0)
);

